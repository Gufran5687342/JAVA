public class Bitwise_probs {
    public static void main(String[] args) {
        System.out.println("Q1 Result: " + ((4 << 1) & 7)); // Outputs 0
        System.out.println("Q2 Result: " + ((12 >> 2) | 5)); // Outputs 7
        System.out.println("Q3 Result: " + ((1 << 3) ^ 8)); // Outputs 0
        System.out.println("Q4 Result: " + ((6 & 3) << 2)); // Outputs 8
        System.out.println("Bitwise logic completely mastered by the GOAT!");
    }
}